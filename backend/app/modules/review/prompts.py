"""复习模块的 LLM prompt 模板"""

FREE_RECALL_ASSESS_PROMPT = """你是一位专业的教师，正在评估学生的"主动回忆"表现。

## 知识单元标题
{unit_title}

## 知识单元摘要
{summary}

## 关键要点（评估基准）
{key_points}

## 核心概念
{concepts}

## 学生的回忆内容
{student_recalled}

## 任务
请将学生的回忆内容与上面的参考内容进行对比，评估回忆质量。

以JSON格式返回：
```json
{{
  "coverage": <0-1, 覆盖了多少关键要点>,
  "accuracy": <0-1, 提到的内容准确度>,
  "depth": <0-1, 解释深度>,
  "overall_score": <0-100综合分>,
  "recalled_points": [
    {{"content": "学生提到的内容", "matched_point": "对应的原始要点", "is_accurate": true}},
    ...
  ],
  "missed_points": ["遗漏的要点1", "遗漏的要点2"],
  "incorrect_points": ["记错的内容描述"],
  "gap_report": "<自然语言的差距报告，150-200字>"
}}
```

评分标准：
- 覆盖率：回忆出了多少原始要点
- 准确性：回忆的内容是否与原始内容一致
- 深度：是否包含了要点的解释和例子，而非仅列出关键词
- gap_report 要具体指出：哪些记住了（肯定）、哪些遗漏了（需复习）、哪些记错了（需纠正）

注意：
- 只要核心意思对，即使表述不同也算覆盖
- 学生可能用不同的顺序回忆，不要求与原始顺序一致
- 如果学生回忆了超出参考范围的正确内容，也应肯定"""
